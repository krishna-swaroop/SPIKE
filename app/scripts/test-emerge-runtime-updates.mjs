import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const source = readFileSync(new URL('../src/emergeRuntimeUpdates.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const { EMergeUpdateController } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const response = data => ({ok:true,result:{contract:'spike/emerge-runtime-update/v1',...data}});
const calls = []; let pollFailure = false;
const controller = new EMergeUpdateController(async request => {
  calls.push(request);
  if(request.method==='check_emerge_update') return response({python_executable:'C:/solver/Scripts/python.exe',installed_version:'3.0.0a19',target_version:'3.1.0',can_update:true});
  if(request.method==='start_emerge_update') return response({operation_id:'update-1',status:'running'});
  if(pollFailure) throw Error('transport interrupted');
  return response({operation_id:'update-1',status:'succeeded',installed_version:'3.1.0',compatibility:{available:true,adapter_evidence:'api_detected'},log:'pip check passed'});
});
await controller.start(); assert.equal(calls.length,0,'no install before a checked target');
await controller.check('  C:/solver/Scripts/python.exe  ','prerelease');
assert.equal(controller.state.status,'checked'); assert.equal(controller.state.requested_python,'C:/solver/Scripts/python.exe');
await controller.start();
assert.deepEqual(calls[1],{method:'start_emerge_update',params:{python_executable:'C:/solver/Scripts/python.exe',channel:'prerelease',target_version:'3.1.0'}},'install pins the exact checked release and interpreter');
controller.invalidate(); assert.equal(controller.state.status,'running','closing/changing panel cannot forget an active install');
await controller.start(); await controller.check('other','stable'); assert.equal(calls.length,2,'duplicate requests blocked while update active');
pollFailure=true; await controller.refresh();
assert.equal(controller.state.status,'running','failed poll never unlocks a possibly active install'); assert.match(controller.state.error,/Recheck status/);
pollFailure=false; await controller.refresh(); assert.equal(controller.state.status,'succeeded'); assert.equal(controller.state.compatibility.available,true);
const stale = []; const racing = new EMergeUpdateController(request => new Promise(resolve => stale.push(resolve)));
const first=racing.check('old','prerelease'); racing.invalidate(); const second=racing.check('new','stable');
stale[1](response({python_executable:'new',can_update:false,reason:'No stable EMerge 3 release'})); await second;
stale[0](response({python_executable:'old',can_update:true,target_version:'3.1'})); await first;
assert.equal(racing.state.python_executable,'new','late checks cannot replace the selected environment'); assert.equal(racing.state.can_update,false);
const malformed = new EMergeUpdateController(async () => ({ok:true,result:{contract:'wrong'}}));
await malformed.check('solver','stable'); assert.equal(malformed.state.status,'failed'); assert.match(malformed.state.error,/unsupported/);
const bundle=await build({entryPoints:[fileURLToPath(new URL('../src/EMergeRuntimeUpdater.tsx',import.meta.url))],bundle:true,write:false,format:'esm',platform:'node',external:['react','react/jsx-runtime','lucide-react'],loader:{'.css':'empty'}});
let ui=bundle.outputFiles[0].text;
for(const [name,path] of [['react/jsx-runtime','react/jsx-runtime.js'],['react','react/index.js'],['lucide-react','lucide-react/dist/cjs/lucide-react.js']]) ui=ui.split(`from "${name}"`).join(`from ${JSON.stringify(new URL('../node_modules/'+path,import.meta.url).href)}`);
const {default:Panel}=await import(`data:text/javascript;base64,${Buffer.from(ui).toString('base64')}`);
const render=state => renderToStaticMarkup(React.createElement(Panel,{controller,state,python:'solver',disabled:false,running:state.status==='running'}));
assert.match(render(controller.state),/runtime API check passed/);
assert.match(render({status:'failed',channel:'prerelease',log:'dependency conflict'}),/role="alert"/);
assert.match(render({status:'running',channel:'prerelease'}),/workspace keeps tracking/);
console.log('EMerge update target pinning, stale responses, duplicate protection, lost-status recovery and panel states passed.');
