import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import { importTestTypescript } from "./import-test-typescript.mjs";
const context = await importTestTypescript("pythonWorkspaceContext");
const templates = await importTestTypescript("pythonWorkspaceTemplates");
const catalog = JSON.parse(readFileSync(new URL("../../schemas/python-workspace-api-v1.json", import.meta.url), "utf8"));
const source = readFileSync(new URL("../src/pythonCompletions.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
const module = { exports: {} };
new Function("require", "module", "exports", compiled)(() => catalog, module, module.exports);
const api = module.exports;
const design = { design_id: "design", name: "Source", nets: [{ id: "gnd", name: "GND" }, { id: "rail", name: "+3V3" }], components: [] };
const workspace = context.pythonWorkspaceContext(design, { boards: [{ id: "A", name: "Controller", design_id: "design" }, { id: "B", name: "Shield", design_id: "design" }] }, { designs: [design] }, "A");
const nets = context.pythonBoardNets(workspace), base = api.pythonBaseSuggestions(templates.PYTHON_TEMPLATES);
const symbols = api.pythonSymbols("supply_voltage = 5\ndef measure(current, resistance):\n    return current * resistance\nimport numpy as np\n# bogus = 1\ntext = 'fake = 2'\nfrom math import sqrt as root");
assert.ok(symbols.some(item => item.label === "supply_voltage" && item.kind === "variable"));
assert.ok(symbols.some(item => item.label === "measure" && item.kind === "function"));
assert.ok(symbols.some(item => item.label === "current"));
assert.ok(symbols.some(item => item.label === "root"));
assert.ok(!symbols.some(item => ["bogus", "fake"].includes(item.label)));
const complete = (code, caret = code.length, explicit = false) => api.pythonCompletion(code, caret, base, symbols, nets, workspace, explicit);
assert.equal(complete("supply_v").items[0].label, "supply_voltage");
assert.equal(complete("pritn").items[0].label, "print", "nearest misspelling ranked");
assert.equal(complete("spike.nets.").items[0].label, "get");
const method = complete("spike.nets.ge"), inserted = api.applyPythonCompletion("spike.nets.ge", method, method.items[0]);
assert.equal(inserted.code, "spike.nets.get(net_id, board_id=board_id)");
assert.equal(inserted.code.slice(inserted.selection.start, inserted.selection.end), "net_id");
assert.ok(!inserted.code.includes("${"));
assert.equal(complete("# spike.", undefined, true), null);
assert.equal(complete("text = 'spike.", undefined, true), null);
assert.equal(complete("text = '''net", undefined, true), null);
assert.equal(complete("import js").items[0].label, "json");
assert.ok(complete("import numpy as np\nnp.li").items.some(item => item.label === "linspace"));
assert.ok(complete("import spike as spi\nspi.nets.ge").items.some(item => item.label === "get"));
assert.ok(complete("from spike import nets as rails\nrails.li").items.some(item => item.label === "list"));
assert.ok(complete("template_thermal").items.some(item => item.kind === "template"));
const named = complete('spike.nets.get(name="G');
assert.equal(named.items[0].label, "GND"); assert.equal(named.items[0].detail, "Controller"); assert.equal(named.items[0].insert, "GND");
const scoped = 'spike.nets.get(name="G", board_id="B")';
assert.equal(complete(scoped, scoped.indexOf('G') + 1).items[0].detail, "Shield", "board scope later in argument list wins");
assert.equal(complete('spike.ui.select_net("B", "G').items[0].detail, "Shield");
assert.equal(complete('spike.boards.get("S').items[0].label, "Shield");
assert.equal(api.applyPythonCompletion("print", complete("print", 2), complete("print", 2).items.find(item => item.label === "print")).code, "print", "replace token suffix when caret is inside a word");
const qualified = context.admittedPythonUiActions([{ action: "select_net", board_id: "B", net_id: "gnd" }], workspace);
assert.equal(qualified[0].board_id, "B");
assert.throws(() => context.admittedPythonUiActions([{ action: "select_net", board_id: "C", net_id: "gnd" }], workspace));
assert.throws(() => context.admittedPythonUiActions([{ action: "open_panel", panel: "delete" }], workspace));
assert.throws(() => context.admittedPythonUiActions(Array(65).fill({ action: "open_panel", panel: "nets" }), workspace));
assert.equal(nets.filter(net => net.name === "GND").length, 2);
assert.notEqual(context.pythonContextKey(workspace), context.pythonContextKey({ ...workspace, selected_board_id: "B" }));
assert.ok(complete("", 0, true).items.length <= 60);
const numericWorkspace = { ...workspace, boards: workspace.boards.map(board => ({ ...board, design: { ...design, nets: [{ id: 17, name: "GND" }] } })) };
const numericNets = context.pythonBoardNets(numericWorkspace);
assert.equal(numericNets[0].id, 17);
assert.deepEqual(context.admittedPythonUiActions([{ action: "select_net", board_id: "B", net_id: 17 }], numericWorkspace), [{ action: "select_net", board_id: "B", net_id: 17 }]);
assert.throws(() => context.admittedPythonUiActions([{ action: "select_net", board_id: "B", net_id: "17" }], numericWorkspace));
const numericCompletion = code => api.pythonCompletion(code, code.length, base, symbols, numericNets, numericWorkspace, true);
assert.equal(numericCompletion('spike.nets.get(').items[0].insert, '17');
assert.equal(numericCompletion('spike.nets.get("G').items.length, 0, "numeric identity must not become a quoted string");
assert.equal(numericCompletion('spike.nets.get(name="G').items[0].insert, 'GND');
console.log("Python completion: nearest ranking, scope, lexical exclusions, snippets, token replacement and interface admission passed.");
