import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ts from 'typescript';
const require = createRequire(import.meta.url);
const source = readFileSync(new URL('../src/AssemblyMechanicalStudyModels.tsx', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const module = { exports: {} };
new Function('require', 'module', 'exports', js)(require, module, module.exports);
const Forms = module.exports.default;
const assembly = { boards: [{ id: 'private-board', name: 'Controller' }], parts: [{ id: 'private-case', name: 'Aluminium housing' }] };
let draft = { part_models: [{ part_id: 'private-case', elements: [{ id: 'body', power_w: 2 }], links: [] }] };
const edit = change => { const copy = structuredClone(draft); change(copy); draft = copy; };
const props = domain => ({ assembly, draft, domain, edit });
const nodes = node => !node || typeof node !== 'object' ? [] : [node, ...React.Children.toArray(node.props?.children).flatMap(nodes)];
let html = renderToStaticMarkup(React.createElement(Forms, props('thermal')));
assert.match(html, /Aluminium housing/); assert.match(html, /Thermal mass/); assert.doesNotMatch(html, /private-case/);
let tree = nodes(Forms(props('thermal')));
const numeric = tree.find(node => node.props?.field === 'thermal_capacitance_j_per_c');
numeric.props.change(12); assert.equal(draft.part_models[0].elements[0].thermal_capacitance_j_per_c, 12);
numeric.props.change(null); assert.equal(draft.part_models[0].elements[0].thermal_capacitance_j_per_c, undefined, 'empty optional path/mass stays absent');
tree.find(node => node.type === 'button' && React.Children.toArray(node.props.children).join('') === 'Add thermal node').props.onClick();
assert.equal(draft.part_models[0].elements.length, 2);
draft = { part_models: [{ part_id: 'private-case', elements: [] }], electrical_bond_models: [{ bond_id: 'private-bond', endpoint_a: { board_id: 'private-board', node: '0' }, endpoint_b: { part_id: 'private-case', node: 'plate' } }] };
html = renderToStaticMarkup(React.createElement(Forms, props('si')));
assert.match(html, /Board and chassis bonds/); assert.match(html, /Controller/); assert.doesNotMatch(html, /private-case|private-board|private-bond/);
tree = nodes(Forms(props('si')));
tree.find(node => node.type === 'button' && React.Children.toArray(node.props.children).join('') === 'Add passive element').props.onClick();
assert.equal(draft.part_models[0].elements[0].type, 'resistor');
nodes(Forms(props('si'))).find(node => node.type === 'select' && node.props['aria-label'] === 'Mechanical element type').props.onChange({ target: { value: 'capacitor' } });
assert.equal(draft.part_models[0].elements[0].capacitance_f, null, 'new type retains a saveable explicit missing numeric property');
tree.find(node => node.type === 'input' && node.props['aria-label'] === 'endpoint_b local node').props.onChange({ target: { value: 'skin' } });
assert.equal(draft.electrical_bond_models[0].endpoint_b.node, 'skin');
assert.equal(Forms(props('emi')), null);
console.log('Mechanical study forms: named structures, thermal mass, passive models and explicit bond node edits passed');
